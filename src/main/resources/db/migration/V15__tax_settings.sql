-- Per-country VAT/tax configuration, managed by admins. Each country has a
-- rate (percent, e.g. 12.00) and a mode: whether the tax is already INCLUDED
-- in listed prices (common in PH/EU) or ADDED on top at checkout (common in US).
CREATE TABLE tax_settings (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    country_code VARCHAR(2)   NOT NULL,
    country_name VARCHAR(100) NOT NULL,
    rate         NUMERIC(6,3) NOT NULL DEFAULT 0,
    inclusive    BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at   TIMESTAMPTZ  NOT NULL,
    updated_at   TIMESTAMPTZ  NOT NULL,
    CONSTRAINT uq_tax_settings_country UNIQUE (country_code)
);

CREATE INDEX idx_tax_settings_country ON tax_settings (country_code);

